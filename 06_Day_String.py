# Day 6- Working with text (Strings)

greeting = "Hello"
name = "Alex"

# Joining strings together
full_greeting = greeting + " " + name
print(full_greeting)

# Changing string case
message = "python is fun"
print(message.upper())
print(message.title())

# Counting letters
sentence = "I am learning Python every day"
print("Number of characters:", len(sentence))

# Replacing words
new_sentence = sentence.replace("Python", "coding")
print(new_sentence)