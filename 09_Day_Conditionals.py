# Day 9 - Making decisions with IF / ELSE

age = 18

if age >= 18:
    print("You are an adult. You can vote!")
else:
    print("You are too young to vote.")

# Checking grades
score = 75

if score >= 80:
    print("Grade: A")
elif score >= 70:
    print("Grade: B")
elif score >= 60:
    print("Grade: C")
else:
    print("Grade: F")