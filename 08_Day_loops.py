# Day 8 - Repeating code with Loops

# FOR loop to print numbers 1 to 5
print("For loop:")
for i in range(1, 6):
    print("Number:", i)

# Loop through a list
colors = ["red", "green", "blue"]
for color in colors:
    print("I like", color)

# WHILE loop
print("While loop:")
count = 1
while count <= 3:
    print("Count is:", count)
    count = count + 1