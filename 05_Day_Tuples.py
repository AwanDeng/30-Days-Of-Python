# Day 6 - Learning about tuples (lists that cannot change)

# Creating a tuple
colors = ("red", "green", "blue")
print("My colors:", colors)

# Accessing items in a tuple
print("First color:", colors[0])

# Joining two tuples
more_colors = ("yellow", "purple")
all_colors = colors + more_colors
print("All colors combined:", all_colors)

# Checking length of tuple
print("Total colors:", len(all_colors))